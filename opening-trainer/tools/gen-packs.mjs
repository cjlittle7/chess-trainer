// Developer tool: builds src/packs.js (the sample opening packs of the tournament hall).
// Each family starts from hand-picked opening theory and is extended to 15 moves by Stockfish playing both sides.
// Usage: node tools/gen-packs.mjs /path/to/stockfish-package   (the npm "stockfish" package folder)
import { createRequire } from "node:module";
import fs from "node:fs";
import { newGame, applyMove, parseLine, lineToSan } from "../src/botplay.js";
import { createStockfish } from "../src/sfengine.js";
import { makeFen } from "chessops/fen";

const require = createRequire(import.meta.url);
const pkg = process.argv[2] || "/tmp/sfprobe/package";
const sf = createStockfish({ idleMs: 1e9, createWorker: () => {
  const w = { onmessage: null, postMessage(c) { e.processCommand(c); }, terminate() { try { e.terminate(); } catch { /* done */ } } };
  const e = require(pkg)("lite-single", (line) => w.onmessage && w.onmessage({ data: line }));
  return w;
} });

const FAMILIES = [
  { id: "open", name: "Open Games",
    white: ["1.e4 e5 2.Nf3 Nc6 3.Bc4 Bc5 4.c3 Nf6 5.d3", "1.e4 c5 2.Nf3 d6 3.d4 cxd4 4.Nxd4 Nf6 5.Nc3", "1.e4 e6 2.d4 d5 3.Nc3 Nf6 4.Bg5 Be7 5.e5"],
    black: ["1.e4 e5 2.Nf3 Nc6 3.Bb5 a6 4.Ba4 Nf6 5.O-O Be7", "1.d4 d5 2.c4 e6 3.Nc3 Nf6 4.Bg5 Be7 5.e3 O-O", "1.c4 e5 2.Nc3 Nf6 3.Nf3 Nc6 4.g3 d5 5.cxd5 Nxd5", "1.Nf3 d5 2.g3 Nf6 3.Bg2 e6 4.O-O Be7 5.d3 O-O"] },
  { id: "qp", name: "Queen's Pawn",
    white: ["1.d4 d5 2.c4 e6 3.Nc3 Nf6 4.Bg5 Be7 5.e3", "1.d4 Nf6 2.c4 g6 3.Nc3 Bg7 4.e4 d6 5.Nf3", "1.d4 d5 2.c4 c6 3.Nf3 Nf6 4.Nc3 dxc4 5.a4"],
    black: ["1.e4 c6 2.d4 d5 3.Nc3 dxe4 4.Nxe4 Bf5 5.Ng3 Bg6", "1.d4 d5 2.c4 c6 3.Nf3 Nf6 4.Nc3 dxc4 5.a4 Bf5", "1.c4 c5 2.Nc3 Nc6 3.g3 g6 4.Bg2 Bg7 5.Nf3 e6", "1.Nf3 Nf6 2.c4 g6 3.Nc3 Bg7 4.e4 d6 5.d4 O-O"] },
  { id: "sharp", name: "Sharp & Flank",
    white: ["1.c4 e5 2.Nc3 Nf6 3.Nf3 Nc6 4.g3 d5 5.cxd5", "1.e4 e5 2.Nf3 Nc6 3.Bb5 a6 4.Ba4 Nf6 5.O-O Be7", "1.e4 c6 2.d4 d5 3.e5 Bf5 4.Nf3 e6 5.Be2"],
    black: ["1.e4 c5 2.Nf3 d6 3.d4 cxd4 4.Nxd4 Nf6 5.Nc3 a6", "1.d4 Nf6 2.c4 g6 3.Nc3 Bg7 4.e4 d6 5.Nf3 O-O", "1.c4 e5 2.Nc3 Nf6 3.Nf3 Nc6 4.g3 d5 5.cxd5 Nxd5", "1.Nf3 Nf6 2.c4 e6 3.Nc3 Bb4 4.Qc2 O-O 5.a3 Bxc3+"] },
];
const MOVES = 15;

async function extend(prefixText) {
  const p = parseLine(prefixText);
  if (!p.ok) throw new Error(prefixText + " -> " + p.error);
  const g = newGame();
  for (const u of p.ucis) applyMove(g, u);
  while (g.ucis.length < MOVES * 2) {
    const r = await sf.think({ fen: makeFen(g.pos.toSetup()), elo: null, movetime: 150 });
    if (!applyMove(g, r.uci)) throw new Error("illegal engine move " + r.uci);
  }
  return lineToSan(g.ucis);
}

const out = [];
for (const f of FAMILIES) {
  const fam = { id: f.id, name: f.name, white: [], black: [] };
  for (const side of ["white", "black"]) for (const t of f[side]) fam[side].push(await extend(t));
  out.push(fam);
}
sf.shutdown();
fs.writeFileSync(new URL("../src/packs.js", import.meta.url), `// Generated by tools/gen-packs.mjs. Sample opening packs: each line is 15 moves; a pack of n moves uses the first n moves of every line.
export const PACK_FAMILIES = ${JSON.stringify(out, null, 2)};
`);
console.log("wrote src/packs.js");
process.exit(0);
